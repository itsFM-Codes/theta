static EvalParams current_params = DEFAULT_EVAL_PARAMS;
static unsigned int current_generation = 1;

const EvalParams *current_eval_params(void) {
    return &current_params;
}

void set_current_eval_params(const EvalParams *params) {
    if (params == 0) {
        return;
    }

    current_params = *params;
    current_generation++;
}

void reset_current_eval_params(void) {
    current_params = DEFAULT_EVAL_PARAMS;
    current_generation++;
}

unsigned int eval_params_generation(void) {
    return current_generation;
}

int eval_piece_type_value(PieceType type) {
    if (type < PIECE_TYPE_NONE || type > PIECE_TYPE_KING) {
        return 0;
    }
    return current_params.piece_values[type];
}

int eval_scale_score(int score, int scale) {
    return score * scale / 256;
}
